package api

import (
	"database/sql"
	"fmt"
	"net"
	"net/http"

	"github.com/go-chi/chi/v5"
	"github.com/go-chi/chi/v5/middleware"
	goredis "github.com/redis/go-redis/v9"
	httpSwagger "github.com/swaggo/http-swagger/v2"
	_ "github.com/user/whatsmeow-basileia/docs" // Docs generated by swaggo
	"github.com/user/whatsmeow-basileia/internal/audit"
	"github.com/user/whatsmeow-basileia/internal/auth"
	"github.com/user/whatsmeow-basileia/internal/infrastructure/rabbitmq"
	"github.com/user/whatsmeow-basileia/internal/infrastructure/storage"
	"github.com/user/whatsmeow-basileia/internal/infrastructure/whatsapp"
	"github.com/user/whatsmeow-basileia/internal/ratelimit"
	"github.com/user/whatsmeow-basileia/pkg/config"
)

type Handler struct {
	manager     *whatsapp.MultiClientManager
	rmqClient   *rabbitmq.Client
	db          *sql.DB
	redis       *goredis.Client
	storage     *storage.Storage
	cfg         *config.Config
	auth        *auth.Service
	audit       *audit.Store
	limiter     *ratelimit.Limiter
	allowedNets []*net.IPNet
}

// Deps groups everything the HTTP layer needs. Optional components (Redis, Storage) may be nil.
type Deps struct {
	Manager  *whatsapp.MultiClientManager
	RabbitMQ *rabbitmq.Client
	DB       *sql.DB
	Redis    *goredis.Client
	Storage  *storage.Storage
	Config   *config.Config
	Auth     *auth.Service
	Audit    *audit.Store
}

func NewHandler(d Deps) (*Handler, error) {
	nets, err := parseCIDRs(d.Config.AllowedCIDRs)
	if err != nil {
		return nil, fmt.Errorf("invalid ALLOWED_CIDRS: %w", err)
	}
	return &Handler{
		manager:     d.Manager,
		rmqClient:   d.RabbitMQ,
		db:          d.DB,
		redis:       d.Redis,
		storage:     d.Storage,
		cfg:         d.Config,
		auth:        d.Auth,
		audit:       d.Audit,
		limiter:     ratelimit.New(d.Redis),
		allowedNets: nets,
	}, nil
}

// Router builds the HTTP routes. Every pre-existing path is kept as-is; the only
// difference is that they now go through authentication and role checks.
func (h *Handler) Router() http.Handler {
	r := chi.NewRouter()
	r.Use(middleware.RequestID)
	if h.cfg.TrustProxy {
		r.Use(middleware.RealIP)
	}
	r.Use(middleware.Recoverer)
	r.Use(middleware.Logger)
	r.Use(securityHeaders)
	r.Use(cors(h.cfg.CORSOrigins))
	r.Use(maxBody(h.cfg.MaxBodyBytes))

	r.Get("/health", h.Health)
	r.Get("/ready", h.Ready)

	r.Get("/docs/*", httpSwagger.Handler(
		httpSwagger.URL("/docs/doc.json"), //The url pointing to API definition
	))

	r.Route("/api", func(apiRouter chi.Router) {
		apiRouter.Get("/health", h.Health)
		apiRouter.Get("/ready", h.Ready)

		apiRouter.Group(func(pr chi.Router) {
			pr.Use(h.ipAllowlist, h.authenticate, h.rateLimit, h.auditTrail)

			pr.Get("/auth/me", h.Me)

			// Read-only (viewer and above, instance tokens see only their instance)
			pr.Group(func(v chi.Router) {
				v.Use(requireRole(auth.RoleViewer))
				v.Get("/device", h.ListDevices)
				v.Get("/device/{id}/status", h.GetStatus)
				v.Get("/stats", h.GetStats)
			})

			// Operator: manage instances and send messages
			pr.Group(func(o chi.Router) {
				o.Use(requireRole(auth.RoleOperator))
				o.Post("/device", h.CreateDevice)
				o.Put("/device/{id}/rename", h.RenameDevice)
				o.Delete("/device/{id}", h.DeleteDevice)
				o.Post("/device/{id}/reconnect", h.ReconnectDevice)
				o.Put("/device/{id}/webhook", h.UpdateDeviceWebhook)
				o.Put("/device/{id}/proxy", h.UpdateDeviceProxy)
				o.Get("/device/{id}/qr", h.GetQR)
				o.Put("/device/{id}/credentials", h.UpdateDeviceCredentials)
				o.Post("/message/send", h.SendText)
				o.Post("/message/interactive/button", h.SendInteractiveButton)
				o.Post("/message/interactive/copy", h.SendInteractiveCopyButton)
				o.Post("/message/media", h.SendMedia)

				// Basileapi compatible routes (Messages only)
				o.Route("/send", func(r chi.Router) {
					r.Post("/text", h.SendUazText)
					r.Post("/media", h.SendUazMedia)
					r.Post("/contact", h.SendUazGeneric)
					r.Post("/location", h.SendUazGeneric)
					r.Post("/status", h.SendUazGeneric)
					r.Post("/menu", h.SendUazGeneric)
					r.Post("/button", h.SendUazGeneric)
					r.Post("/poll", h.SendUazGeneric)
					r.Post("/carousel", h.SendUazGeneric)
					r.Post("/location-button", h.SendUazGeneric)
					r.Post("/request-payment", h.SendUazGeneric)
					r.Post("/pix-button", h.SendUazGeneric)
				})
				// Documented in SendUazGeneric but was never routed before.
				o.Post("/message/presence", h.SendUazGeneric)
			})

			// Admin
			pr.Group(func(a chi.Router) {
				a.Use(requireRole(auth.RoleAdmin))
				a.Get("/logs", h.GetLogs)
				a.Get("/audit", h.ListAudit)

				// Debug endpoints for testing buttons and lists
				a.Post("/debug/send-button", h.DebugSendButton)
				a.Post("/debug/send-list", h.DebugSendList)
			})

			// Key management requires an admin key that is not limited to instances.
			pr.Group(func(a chi.Router) {
				a.Use(requireGlobalAdmin)
				a.Get("/auth/keys", h.ListAPIKeys)
				a.Post("/auth/keys", h.CreateAPIKey)
				a.Put("/auth/keys/{id}", h.UpdateAPIKey)
				a.Delete("/auth/keys/{id}", h.DeleteAPIKey)
			})
		})
	})

	return r
}
